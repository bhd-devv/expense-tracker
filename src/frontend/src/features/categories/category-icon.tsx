const defaults: Record<string, string> = {
  food: "utensils-crossed",
  transport: "car-front",
  shopping: "shopping-bag",
  home: "house",
  health: "heart-pulse",
  leisure: "ticket",
  other: "receipt-text",
};
export function categoryIconId(icon?: string | null, code?: string | null) {
  return icon ?? (code ? defaults[code] : undefined) ?? "tags";
}
export function CategoryIcon({
  icon,
  code,
}: {
  icon?: string | null;
  code?: string | null;
}) {
  const id = categoryIconId(icon, code);
  const Icon = Object.hasOwn(icons, id) ? icons[id] : Tags;
  return <Icon size={22} strokeWidth={1.8} aria-hidden="true" />;
}
